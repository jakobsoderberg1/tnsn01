"""
Plan a full-coverage route (Chinese Postman) over the maze and export it
as a C header for the Arduino.

    python3 plan_route.py            -> writes route.h, route.txt, graph_check.png, route_overlay.png
"""
import itertools
import networkx as nx
from PIL import Image, ImageDraw, ImageFont

from maze_graph import (NODES, EDGES, BASE, START_HEADING, BLIND_NODES,
                        KNOWN_ITEMS, MM_PER_PX)

DIRS = "NESW"
TURN_NAME = {0: "S", 1: "R", 2: "B", 3: "L"}


def direction(u, v):
    (x1, y1), (x2, y2) = NODES[u], NODES[v]
    if x1 == x2:
        return "N" if y2 < y1 else "S"
    if y1 == y2:
        return "E" if x2 > x1 else "W"
    raise ValueError(f"Edge {u}-{v} is not axis-aligned: {NODES[u]} {NODES[v]}")


def length(u, v):
    (x1, y1), (x2, y2) = NODES[u], NODES[v]
    return abs(x1 - x2) + abs(y1 - y2)


def build_graph():
    g = nx.Graph()
    for n in NODES:
        g.add_node(n)
    for u, v, gaps in EDGES:
        g.add_edge(u, v, weight=length(u, v), gaps={u: gaps,
                   v: [(length(u, v) - e, length(u, v) - s) for s, e in gaps]})
    # sanity: at most one neighbour per direction
    for n in g.nodes:
        seen = {}
        for m in g.neighbors(n):
            d = direction(n, m)
            assert d not in seen, f"{n} has two neighbours to the {d}: {seen[d]}, {m}"
            seen[d] = m
    assert nx.is_connected(g), "graph is not connected"
    return g


def chinese_postman(g, start):
    odd = [n for n in g.nodes if g.degree(n) % 2]
    dist = dict(nx.all_pairs_dijkstra_path_length(g))
    k = nx.Graph()
    for a, b in itertools.combinations(odd, 2):
        k.add_edge(a, b, weight=dist[a][b])
    matching = nx.min_weight_matching(k)
    mg = nx.MultiGraph(g)
    for a, b in matching:
        path = nx.dijkstra_path(g, a, b)
        for u, v in zip(path, path[1:]):
            mg.add_edge(u, v, weight=g[u][v]["weight"])
    circuit = [u for u, _ in nx.eulerian_circuit(mg, source=start)] + [start]
    return circuit


def simulate(g, route):
    """Turn sequence the robot will execute, plus coverage check."""
    heading = START_HEADING
    assert direction(route[0], route[1]) == heading, "first edge must match START_HEADING"
    steps, covered, total = [], set(), 0
    for i in range(1, len(route)):
        prev, node = route[i - 1], route[i]
        covered.add(frozenset((prev, node)))
        total += g[prev][node]["weight"]
        heading = direction(prev, node)
        if i + 1 < len(route):
            nxt = direction(node, route[i + 1])
            turn = TURN_NAME[(DIRS.index(nxt) - DIRS.index(heading)) % 4]
        else:
            turn = "-"  # home
        steps.append((node, turn))
    missing = [e for e in g.edges if frozenset(e) not in covered]
    assert not missing, f"edges not covered: {missing}"
    return steps, total


def write_header(g, route, path="route.h"):
    names = list(NODES)
    idx = {n: i for i, n in enumerate(names)}
    mm = lambda px: int(round(px * MM_PER_PX))
    lines = [
        "// Generated by plan_route.py - do not edit by hand.",
        "#pragma once",
        "#include <avr/pgmspace.h>",
        "",
        f"#define NUM_NODES {len(names)}",
        f"#define ROUTE_LEN {len(route)}",
        f"#define BASE_NODE {idx[BASE]}",
        f"#define START_HEADING {DIRS.index(START_HEADING)}  // 0=N 1=E 2=S 3=W",
        "#define NO_NODE 255",
        "",
        "// Node flags",
        "#define NF_DEADEND 1",
        "#define NF_CORNER  2",
        "#define NF_BLIND   4   // junction with no line under it",
        "",
        "struct Node {",
        "  uint8_t  nb[4];        // neighbour index per direction N,E,S,W (NO_NODE = none)",
        "  uint16_t len[4];       // edge length in mm",
        "  uint16_t gapStart[4];  // mm from this node where the line disappears (0 and gapEnd 0 = no gap)",
        "  uint16_t gapEnd[4];    // mm from this node where the line comes back",
        "  uint8_t  flags;",
        "};",
        "",
        "const Node NODES[NUM_NODES] PROGMEM = {",
    ]
    for n in names:
        nb, ln, gs, ge = ["NO_NODE"] * 4, [0] * 4, [0] * 4, [0] * 4
        for m in g.neighbors(n):
            d = DIRS.index(direction(n, m))
            nb[d], ln[d] = str(idx[m]), mm(g[n][m]["weight"])
            gaps = g[n][m]["gaps"][n]
            if gaps:
                gs[d], ge[d] = mm(gaps[0][0]), mm(gaps[0][1])
        deg = g.degree(n)
        flags = []
        if deg == 1:
            flags.append("NF_DEADEND")
        if deg == 2 and len({direction(n, m) in "NS" for m in g.neighbors(n)}) == 2:
            flags.append("NF_CORNER")
        if n in BLIND_NODES:
            flags.append("NF_BLIND")
        f = "|".join(flags) or "0"
        lines.append(f"  {{{{{', '.join(nb)}}}, {{{', '.join(map(str, ln))}}}, "
                     f"{{{', '.join(map(str, gs))}}}, {{{', '.join(map(str, ge))}}}, {f}}},  // {idx[n]:2d} {n}")
    lines += ["};", "", "// Full-coverage route as node indices, starts and ends at base",
              "const uint8_t ROUTE[ROUTE_LEN] PROGMEM = {"]
    for i in range(0, len(route), 16):
        lines.append("  " + ", ".join(f"{idx[n]:2d}" for n in route[i:i + 16]) + ",")
    lines += ["};", ""]
    lines.append("// Node names (debug output)")
    lines.append("const char* const NODE_NAMES[NUM_NODES] = {" +
                 ", ".join(f'"{n}"' for n in names) + "};")
    open(path, "w").write("\n".join(lines) + "\n")


def draw(g, route=None, out="graph_check.png"):
    img = Image.open("map.png").convert("RGB")
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype("DejaVuSans-Bold.ttf", 15)
    except OSError:
        font = ImageFont.load_default()
    for u, v, data in g.edges(data=True):
        (x1, y1), (x2, y2) = NODES[u], NODES[v]
        d.line([(x1, y1), (x2, y2)], fill=(30, 110, 230), width=5)
        L = data["weight"]
        for s, e in data["gaps"][u]:
            t0, t1 = s / L, e / L
            d.line([(x1 + (x2 - x1) * t0, y1 + (y2 - y1) * t0),
                    (x1 + (x2 - x1) * t1, y1 + (y2 - y1) * t1)], fill=(230, 40, 40), width=9)
    for n, (x, y) in NODES.items():
        col = (0, 170, 0) if n == BASE else (230, 120, 0) if n in BLIND_NODES else (20, 20, 20)
        d.ellipse([x - 7, y - 7, x + 7, y + 7], fill=col)
        d.text((x + 8, y - 20), n, fill=col, font=font)
    for _, _, (x, y) in KNOWN_ITEMS:
        d.ellipse([x - 10, y - 10, x + 10, y + 10], outline=(200, 0, 200), width=3)
    if route:
        # step numbers at each arrival
        counts = {}
        for i, n in enumerate(route[1:], 1):
            x, y = NODES[n]
            k = counts.get(n, 0)
            counts[n] = k + 1
            d.text((x + 8, y + 2 + 15 * k), str(i), fill=(120, 0, 160), font=font)
    img.save(out)


if __name__ == "__main__":
    g = build_graph()
    route = chinese_postman(g, BASE)
    steps, total = simulate(g, route)
    write_header(g, route)
    draw(g, out="graph_check.png")
    draw(g, route, out="route_overlay.png")
    base_len = sum(d["weight"] for *_, d in g.edges(data=True))
    with open("route.txt", "w") as f:
        f.write(f"Total line length: {base_len} px, route length: {total} px "
                f"({total / base_len:.2f}x), {len(steps)} nodes visited\n\n")
        for i, (n, t) in enumerate(steps, 1):
            f.write(f"{i:3d}  arrive {n:4s} -> {t}\n")
    print(open("route.txt").read())
